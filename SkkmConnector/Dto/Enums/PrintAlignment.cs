namespace SkkmConnector
{
    /// <summary>
    /// Выравнивание строки или штрихкода при печати:
    /// <para>
    /// Left - По левому краю
    /// </para>
    /// <para>
    /// Right - По правому краю
    /// </para>
    /// <para>
    /// Center - По центру
    /// </para>
    /// <para>
    /// Width - На всю ширину
    /// </para>
    /// </summary>
    public enum PrintAlignment
    {
        /// <summary>
        /// По левому краю
        /// </summary>
        Left,

        /// <summary>
        /// По правому краю
        /// </summary>
        Right,

        /// <summary>
        /// По центру
        /// </summary>
        Center,

        /// <summary>
        /// На всю ширину
        /// </summary>
        Width,
    }
}
