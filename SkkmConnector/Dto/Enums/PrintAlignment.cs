namespace SkkmConnector
{
    /// <summary>
    /// Выравнивание строки или штрихкода при печати
    /// </summary>
    public enum PrintAlignment
    {
        /// <summary>
        /// По левому краю
        /// </summary>
        Left,

        /// <summary>
        /// По правому краю
        /// </summary>
        Right,

        /// <summary>
        /// По центру
        /// </summary>
        Center,

        /// <summary>
        /// На всю ширину
        /// </summary>
        Width,
    }
}
