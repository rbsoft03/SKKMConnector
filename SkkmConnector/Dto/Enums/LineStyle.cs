namespace SkkmConnector
{
    /// <summary>
    /// Стиль разделительной линии:
    /// <para>
    /// Solid - Сплошная линия (по умолчанию)
    /// </para>
    /// <para>
    /// Bold - Жирная линия
    /// </para>
    /// <para>
    /// Dashed - Штриховая линия
    /// </para>
    /// <para>
    /// Dotted - Пунктирная линия
    /// </para>
    /// <para>
    /// Double - Двойная линия
    /// </para>
    /// </summary>
    public enum LineStyle
    {
        /// <summary>
        /// Сплошная линия (по умолчанию).
        /// </summary>
        Solid,

        /// <summary>
        /// Жирная линия.
        /// </summary>
        Bold,

        /// <summary>
        /// Штриховая линия.
        /// </summary>
        Dashed,

        /// <summary>
        /// Пунктирная линия.
        /// </summary>
        Dotted,

        /// <summary>
        /// Двойная линия.
        /// </summary>
        Double,
    }
}
